const now = Date.now();
const daysAgoIso = (days: number) => new Date(now - days * 24 * 60 * 60 * 1000).toISOString();
const hoursAgoDate = (hours: number) => new Date(now - hours * 60 * 60 * 1000);

function buildUser(
  base: Omit<UserProfile, 'availabilityStatus' | 'heroBadge' | 'lastActiveAt' | 'createdAt'>
): UserProfile {
  const cooldown = evaluateCooldown(base.lastDonationDate, base.manualAvailable);
  return {
    ...base,
    availabilityStatus: cooldown.effectiveStatus,
    heroBadge: computeHeroBadge(base.totalDonations),
    lastActiveAt: daysAgoIso(0),
    createdAt: daysAgoIso(200),
  };
}

